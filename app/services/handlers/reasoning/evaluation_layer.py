"""Evaluation Layer for Tree of Thought Processing.

This module provides evaluation and scoring capabilities for different reasoning paths
generated by the Tree of Thought system.
"""

import json
import logging
from typing import Dict, List, Any, Optional, Tuple
from dataclasses import dataclass
import time

# Configure logging
logger = logging.getLogger(__name__)

@dataclass
class EvaluationMetrics:
    """Data class for evaluation metrics."""
    relevance_score: float
    completeness_score: float
    accuracy_score: float
    clarity_score: float
    overall_score: float
    reasoning: str
    evaluation_time: float

class EvaluationLayer:
    """Evaluation layer for assessing reasoning path quality."""
    
    def __init__(self, llm, config: Optional[Dict[str, Any]] = None):
        """
        Initialize evaluation layer.
        
        Args:
            llm: Language model for evaluation
            config: Configuration parameters
        """
        self.llm = llm
        self.config = config or {}
        self.weights = self.config.get('evaluation_weights', {
            'relevance': 0.3,
            'completeness': 0.25,
            'accuracy': 0.25,
            'clarity': 0.2
        })
        
        logger.info("EvaluationLayer initialized with weights: %s", self.weights)
    
    def evaluate_path(self, path: Dict[str, Any], task_type: str = "theory") -> Dict[str, Any]:
        """
        Evaluate a single reasoning path.
        
        Args:
            path: Path data containing response and reasoning
            task_type: Type of task (theory/calculation)
            
        Returns:
            Evaluation results with scores and metrics
        """
        start_time = time.time()
        
        try:
            logger.debug("Evaluating path of type: %s", path.get('path_type', 'unknown'))
            
            # Create evaluation prompt
            evaluation_prompt = self._create_evaluation_prompt(path, task_type)
            
            # Get LLM evaluation
            response = self.llm.invoke(evaluation_prompt)
            evaluation_data = json.loads(response.content)
            
            # Calculate overall score
            overall_score = self._calculate_overall_score(evaluation_data)
            evaluation_data['overall_score'] = overall_score
            
            # Add timing information
            evaluation_time = time.time() - start_time
            evaluation_data['evaluation_time'] = evaluation_time
            
            logger.debug("Path evaluation completed. Overall score: %.3f", overall_score)
            
            return evaluation_data
            
        except Exception as e:
            logger.error("Error evaluating path: %s", str(e))
            return self._create_fallback_evaluation()
    
    def evaluate_multiple_paths(self, paths: List[Dict[str, Any]], 
                              task_type: str = "theory") -> List[Dict[str, Any]]:
        """
        Evaluate multiple reasoning paths.
        
        Args:
            paths: List of path data
            task_type: Type of task
            
        Returns:
            List of evaluation results
        """
        logger.info("Evaluating %d paths for task type: %s", len(paths), task_type)
        
        evaluations = []
        for i, path in enumerate(paths):
            try:
                evaluation = self.evaluate_path(path, task_type)
                evaluation['path_index'] = i
                evaluations.append(evaluation)
                
            except Exception as e:
                logger.error("Error evaluating path %d: %s", i, str(e))
                fallback_eval = self._create_fallback_evaluation()
                fallback_eval['path_index'] = i
                evaluations.append(fallback_eval)
        
        return evaluations
    
    def _create_evaluation_prompt(self, path: Dict[str, Any], task_type: str) -> str:
        """
        Create evaluation prompt for LLM.
        
        Args:
            path: Path data to evaluate
            task_type: Type of task
            
        Returns:
            Formatted evaluation prompt
        """
        response_text = path.get('response', '')
        reasoning_text = path.get('reasoning', '')
        path_type = path.get('path_type', 'unknown')
        
        if task_type == "calculation":
            criteria_text = """
            - Relevance: Seberapa relevan jawaban dengan pertanyaan perhitungan (0.0-1.0)
            - Completeness: Kelengkapan langkah perhitungan dan formula (0.0-1.0)
            - Accuracy: Ketepatan perhitungan dan hasil numerik (0.0-1.0)
            - Clarity: Kejelasan penjelasan dan struktur jawaban (0.0-1.0)
            """
        else:
            criteria_text = """
            - Relevance: Seberapa relevan jawaban dengan pertanyaan teoritis (0.0-1.0)
            - Completeness: Kelengkapan informasi dan konsep yang dijelaskan (0.0-1.0)
            - Accuracy: Ketepatan informasi aktuaria dan konsep (0.0-1.0)
            - Clarity: Kejelasan penjelasan dan mudah dipahami (0.0-1.0)
            """
        
        prompt = f"""
        Anda adalah evaluator ahli untuk sistem reasoning aktuaria. Evaluasi kualitas jawaban berikut:
        
        TIPE PATH: {path_type}
        JAWABAN: {response_text}
        REASONING: {reasoning_text}
        
        KRITERIA EVALUASI:
        {criteria_text}
        
        INSTRUKSI:
        - Berikan skor 0.0-1.0 untuk setiap kriteria
        - Berikan reasoning singkat untuk penilaian
        - Output dalam format JSON yang valid
        
        FORMAT OUTPUT:
        {{
            "relevance_score": 0.0,
            "completeness_score": 0.0,
            "accuracy_score": 0.0,
            "clarity_score": 0.0,
            "reasoning": "Penjelasan singkat penilaian..."
        }}
        """
        
        return prompt
    
    def _calculate_overall_score(self, evaluation_data: Dict[str, Any]) -> float:
        """
        Calculate weighted overall score.
        
        Args:
            evaluation_data: Individual criterion scores
            
        Returns:
            Weighted overall score
        """
        try:
            overall_score = (
                evaluation_data.get('relevance_score', 0.0) * self.weights['relevance'] +
                evaluation_data.get('completeness_score', 0.0) * self.weights['completeness'] +
                evaluation_data.get('accuracy_score', 0.0) * self.weights['accuracy'] +
                evaluation_data.get('clarity_score', 0.0) * self.weights['clarity']
            )
            
            return round(overall_score, 3)
            
        except Exception as e:
            logger.error("Error calculating overall score: %s", str(e))
            return 0.5  # Default fallback score
    
    def _create_fallback_evaluation(self) -> Dict[str, Any]:
        """
        Create fallback evaluation when LLM evaluation fails.
        
        Returns:
            Default evaluation scores
        """
        return {
            "relevance_score": 0.5,
            "completeness_score": 0.5,
            "accuracy_score": 0.5,
            "clarity_score": 0.5,
            "overall_score": 0.5,
            "reasoning": "Fallback evaluation due to processing error",
            "evaluation_time": 0.0,
            "is_fallback": True
        }
    
    def rank_paths(self, evaluated_paths: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        """
        Rank paths by evaluation scores.
        
        Args:
            evaluated_paths: List of evaluated paths
            
        Returns:
            Sorted list of paths by score (highest first)
        """
        try:
            # Sort by overall_score in descending order
            ranked_paths = sorted(
                evaluated_paths,
                key=lambda x: x.get('overall_score', 0.0),
                reverse=True
            )
            
            # Add ranking information
            for i, path in enumerate(ranked_paths):
                path['rank'] = i + 1
            
            logger.info("Ranked %d paths. Best score: %.3f", 
                       len(ranked_paths), 
                       ranked_paths[0].get('overall_score', 0.0) if ranked_paths else 0.0)
            
            return ranked_paths
            
        except Exception as e:
            logger.error("Error ranking paths: %s", str(e))
            return evaluated_paths
    
    def get_best_path(self, evaluated_paths: List[Dict[str, Any]]) -> Optional[Dict[str, Any]]:
        """
        Get the best evaluated path.
        
        Args:
            evaluated_paths: List of evaluated paths
            
        Returns:
            Best path or None if no paths available
        """
        if not evaluated_paths:
            return None
        
        ranked_paths = self.rank_paths(evaluated_paths)
        best_path = ranked_paths[0] if ranked_paths else None
        
        if best_path:
            logger.info("Best path selected with score: %.3f", 
                       best_path.get('overall_score', 0.0))
        
        return best_path